// Copies ABIs from ../shared/abi (produced by `make abi`) into a typed TS module for viem.
import { readFileSync, writeFileSync } from "node:fs";
const names = { registryAbi: "ReceivableRegistry", buyerRegistryAbi: "BuyerRegistry", tvndAbi: "MockTVND" };
let out = "// Generated by scripts/gen-abi.mjs from shared/abi. Do not edit.\n";
for (const [exp, file] of Object.entries(names)) {
  const abi = readFileSync(new URL(`../../shared/abi/${file}.json`, import.meta.url), "utf8");
  out += `export const ${exp} = ${abi.trim()} as const;\n`;
}
writeFileSync(new URL("../src/lib/abi.ts", import.meta.url), out);
console.log("wrote src/lib/abi.ts");
